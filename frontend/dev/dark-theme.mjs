// Derives src/theme-dark.css from style.css and ui.css: every light colour
// becomes its dark counterpart (same hue, mirrored lightness), scoped under
// :root[data-theme="dark"]. Run `node dev/dark-theme.mjs` after changing
// colours; dev/dark-theme.test.mjs fails while the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const COLOR_PROPS = /^(color|background|background-color|border|border-top|border-right|border-bottom|border-left|border-color|border-left-color|outline|outline-color|box-shadow|fill|stroke|accent-color|caret-color|--[\w-]+)$/u;
// Surfaces that are dark by design keep their colours in both themes.
const KEEP = /::backdrop|\.ui-chip-toggle\.on \.ui-chip-count|\.ui-toast|\.sidebar|\.nav\b|\.nav |\.brand|\.workspace-tag|\.sidebar-note|\.version|\.status-dot|\.ui-chart-tip|\.decision-command|\.ui-pem|\.ui-crash pre|\.login-visual|\.brand-mark/u;

function hexToHsl(hex) {
  let value = hex.slice(1);
  if (value.length === 3 || value.length === 4) value = [...value].map(c => c + c).join('');
  const alpha = value.length === 8 ? value.slice(6) : '';
  const [r, g, b] = [0, 2, 4].map(i => parseInt(value.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b); const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0; let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h /= 6;
  }
  return { h, s, l, alpha };
}

function hslToHex({ h, s, l, alpha }) {
  const f = n => {
    const k = (n + h * 12) % 12;
    const a = s * Math.min(l, 1 - l);
    return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}${alpha}`;
}

/** Light surfaces become dark ones, dark ink becomes light, accents brighten when used as text. */
export function darkColor(hex, property) {
  const c = hexToHsl(hex);
  const isText = property === 'color' || property === 'fill' || property === 'stroke' || property === 'caret-color';
  // Neutral whites and greys take the console's blue-grey tint.
  const tint = c.s < 0.08 ? { h: 0.58, s: 0.28 } : { h: c.h, s: Math.min(c.s, 0.45) };
  if (c.l >= 0.84) return hslToHex({ ...c, ...tint, l: 0.1 + (1 - c.l) * 1.15 });
  if (c.l <= (isText ? 0.4 : 0.2)) return hslToHex({ ...c, s: Math.min(c.s, 0.35), l: 0.93 - c.l * 0.45 });
  if (isText) return hslToHex({ ...c, l: Math.max(c.l, 0.68) });
  return hex;
}

function mapValue(value, property) {
  return value.replace(/#[0-9a-fA-F]{3,8}\b/gu, hex => darkColor(hex, property));
}

function scope(selector) {
  return selector.split(',').map(part => {
    const s = part.trim();
    if (s === ':root' || s.startsWith(':root:')) return `:root[data-theme="dark"]${s.slice(5)}`;
    if (s === 'body' || s.startsWith('body ') || s.startsWith('body.')) return `:root[data-theme="dark"] ${s}`;
    return `:root[data-theme="dark"] ${s}`;
  }).join(', ');
}

function rules(css) {
  const out = [];
  const text = css.replace(/\/\*[\s\S]*?\*\//gu, '');
  let i = 0;
  const readBlock = start => { let depth = 0; for (let j = start; j < text.length; j++) { if (text[j] === '{') depth++; else if (text[j] === '}') { depth--; if (depth === 0) return j; } } return text.length; };
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    const close = readBlock(open);
    const body = text.slice(open + 1, close);
    if (head.startsWith('@media')) out.push({ media: head, children: rules(body) });
    else if (!head.startsWith('@')) out.push({ selector: head, body });
    i = close + 1;
  }
  return out;
}

function emit(list) {
  const lines = [];
  for (const rule of list) {
    if (rule.media) {
      const inner = emit(rule.children);
      if (inner.length) lines.push(`${rule.media} {`, ...inner.map(line => `  ${line}`), '}');
      continue;
    }
    if (KEEP.test(rule.selector)) continue;
    const declarations = rule.body.split(';').map(d => d.trim()).filter(Boolean).flatMap(declaration => {
      const colon = declaration.indexOf(':');
      if (colon < 0) return [];
      const property = declaration.slice(0, colon).trim();
      const value = declaration.slice(colon + 1).trim();
      if (!COLOR_PROPS.test(property) || !/#[0-9a-fA-F]{3,8}\b/u.test(value)) return [];
      const mapped = mapValue(value, property);
      return mapped === value ? [] : [`${property}: ${mapped}`];
    });
    if (declarations.length) lines.push(`${scope(rule.selector)} { ${declarations.join('; ')}; }`);
  }
  return lines;
}

export function buildDarkTheme(sources) {
  const header = '/* Generated by dev/dark-theme.mjs from style.css and ui.css. Do not edit by hand. */';
  const base = ':root[data-theme="dark"] { color-scheme: dark; }';
  return [header, base, ...sources.flatMap(css => emit(rules(css)))].join('\n') + '\n';
}

const here = dirname => fileURLToPath(new URL(dirname, import.meta.url));
export function currentSources() {
  return [readFileSync(here('../src/style.css'), 'utf8'), readFileSync(here('../src/ui.css'), 'utf8')];
}
export const OUTPUT = here('../src/theme-dark.css');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, buildDarkTheme(currentSources()));
  console.log(`Wrote ${OUTPUT}`);
}
