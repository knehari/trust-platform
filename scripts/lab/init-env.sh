#!/bin/sh
set -eu

# Creates, or completes, the private .env.lab of the disposable laboratory
# stack. Existing values are never replaced: rotating a database password
# underneath a running volume would lock the stack out. Values missing from
# an older .env.lab (such as the Keycloak credentials) are appended.
cd "$(dirname "$0")/../.."
umask 077
[ -e .env.lab ] || : > .env.lab
added=0
for name in TRUST_LAB_DB_PASSWORD TRUST_LAB_API_PASSWORD TRUST_LAB_WRITER_PASSWORD TRUST_LAB_SIGNER_PASSWORD TRUST_LAB_PUBLISHER_PASSWORD TRUST_LAB_KC_ADMIN_PASSWORD \
    TRUST_LAB_HSM_PIN TRUST_LAB_HSM_AUDIT_PIN TRUST_LAB_HSM_SO_PIN \
    TRUST_LAB_WORKLOAD_SECRET \
    TRUST_LAB_PW_READER TRUST_LAB_PW_EDITOR TRUST_LAB_PW_APPROVER_1 TRUST_LAB_PW_APPROVER_2 \
    TRUST_LAB_PW_OPERATOR TRUST_LAB_PW_OUTSIDER TRUST_LAB_PW_DISABLED TRUST_LAB_PW_OTHER_CA \
    TRUST_LAB_PW_FOREIGN TRUST_LAB_PW_AUTHOR TRUST_LAB_PW_CA_ADMIN \
    TRUST_LAB_PW_CA_APPROVER_1 TRUST_LAB_PW_CA_APPROVER_2 TRUST_LAB_PW_REQUESTER TRUST_LAB_PW_RA_OFFICER TRUST_LAB_PW_RA_OFFICER_2; do
  if ! grep -q "^${name}=" .env.lab; then
    printf '%s=%s\n' "$name" "$(openssl rand -hex 24)" >> .env.lab
    added=$((added + 1))
  fi
done

# Laboratory approver keys: one P-256 key per profile approver (ADR-0011)
# and per CA approver (ADR-0014), generated by OpenSSL into the ignored
# .lab-keys/ directory. Only the public point (uncompressed SEC1, hex) goes
# into .env.lab, for the database to register. These software keys are for
# the disposable laboratory only.
# Proposed CA roots (scripts/lab/create-lab-root.sh) keep their software
# keys in .lab-keys/ca/. The lab issuing CA's key is generated instead in the
# signer's SoftHSM2 token (scripts/lab/create-lab-root-hsm.sh, ADR-0034) and
# never reaches the host.
mkdir -p .lab-keys/ca
chmod 700 .lab-keys .lab-keys/ca
# Registration officers sign their decisions on certificate applications
# with their own keys (ADR-0028); the signer verifies those signatures.
for approver in approver-1:APPROVER_1 approver-2:APPROVER_2 ca-approver-1:CA_APPROVER_1 ca-approver-2:CA_APPROVER_2 \
    ra-officer:RA_OFFICER ra-officer-2:RA_OFFICER_2; do
  key=".lab-keys/lab-${approver%%:*}.pem"
  name="TRUST_LAB_${approver#*:}_SEC1"
  if [ ! -s "$key" ]; then
    openssl ecparam -name prime256v1 -genkey -noout -out "$key"
    sed -i.bak "/^${name}=/d" .env.lab && rm -f .env.lab.bak
  fi
  chmod 600 "$key"
  if ! grep -q "^${name}=" .env.lab; then
    point=$(openssl ec -in "$key" -pubout -outform DER -conv_form uncompressed 2>/dev/null \
      | tail -c 65 | od -An -v -tx1 | tr -d ' \n')
    case "$point" in
      04????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????) ;;
      *) echo "Could not read the public key of $key" >&2; exit 1 ;;
    esac
    printf '%s=%s\n' "$name" "$point" >> .env.lab
    added=$((added + 1))
  fi
done
# The lab signer's audit key (ADR-0023) is generated in its own SoftHSM2
# token, separate from the CA's (ADR-0035), by
# scripts/lab/create-audit-key-hsm.sh, which writes only its public key to
# .lab-keys/audit/audit-checkpoint.pub.pem for lab_verify_audit_chain.
mkdir -p .lab-keys/audit
chmod 700 .lab-keys/audit
# Database TLS (ADR-0031): a laboratory CA for service certificates and the
# PostgreSQL server certificate (db, localhost, 127.0.0.1). Clients trust only
# tls/ca.crt; the CA key never leaves .lab-keys/ and is mounted nowhere.
mkdir -p .lab-keys/tls
chmod 700 .lab-keys/tls
if [ ! -s .lab-keys/tls/ca.key ] || [ ! -s .lab-keys/tls/ca.crt ]; then
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -days 365 \
    -subj '/CN=Trust Lab Service CA' -keyout .lab-keys/tls/ca.key -out .lab-keys/tls/ca.crt \
    -addext basicConstraints=critical,CA:TRUE,pathlen:0 -addext keyUsage=critical,keyCertSign,cRLSign 2>/dev/null
  rm -f .lab-keys/tls/db.crt
fi
if [ ! -s .lab-keys/tls/db.crt ] || [ ! -s .lab-keys/tls/db.key ]; then
  openssl req -new -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -subj '/CN=db' \
    -keyout .lab-keys/tls/db.key -out .lab-keys/tls/db.csr 2>/dev/null
  printf 'subjectAltName=DNS:db,DNS:localhost,IP:127.0.0.1\nextendedKeyUsage=serverAuth\nkeyUsage=critical,digitalSignature\n' \
    > .lab-keys/tls/db.ext
  openssl x509 -req -in .lab-keys/tls/db.csr -CA .lab-keys/tls/ca.crt -CAkey .lab-keys/tls/ca.key \
    -CAcreateserial -days 90 -extfile .lab-keys/tls/db.ext -out .lab-keys/tls/db.crt 2>/dev/null
  rm -f .lab-keys/tls/db.csr .lab-keys/tls/db.ext
fi
# The management API's HTTPS certificate (ADR-0032): localhost, 127.0.0.1 and
# issuer (the compose service whose network namespace the API shares).
if [ ! -s .lab-keys/tls/api.crt ] || [ ! -s .lab-keys/tls/api.key ]; then
  openssl req -new -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -subj '/CN=trust-api' \
    -keyout .lab-keys/tls/api.key -out .lab-keys/tls/api.csr 2>/dev/null
  printf 'subjectAltName=DNS:localhost,DNS:issuer,IP:127.0.0.1\nextendedKeyUsage=serverAuth\nkeyUsage=critical,digitalSignature\n' \
    > .lab-keys/tls/api.ext
  openssl x509 -req -in .lab-keys/tls/api.csr -CA .lab-keys/tls/ca.crt -CAkey .lab-keys/tls/ca.key \
    -CAcreateserial -days 90 -extfile .lab-keys/tls/api.ext -out .lab-keys/tls/api.crt 2>/dev/null
  rm -f .lab-keys/tls/api.csr .lab-keys/tls/api.ext
fi
# Keycloak's HTTPS certificate (ADR-0033): localhost, 127.0.0.1 and issuer.
if [ ! -s .lab-keys/tls/idp.crt ] || [ ! -s .lab-keys/tls/idp.key ]; then
  openssl req -new -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -subj '/CN=trust-lab-idp' \
    -keyout .lab-keys/tls/idp.key -out .lab-keys/tls/idp.csr 2>/dev/null
  printf 'subjectAltName=DNS:localhost,DNS:issuer,IP:127.0.0.1\nextendedKeyUsage=serverAuth\nkeyUsage=critical,digitalSignature\n' \
    > .lab-keys/tls/idp.ext
  openssl x509 -req -in .lab-keys/tls/idp.csr -CA .lab-keys/tls/ca.crt -CAkey .lab-keys/tls/ca.key \
    -CAcreateserial -days 90 -extfile .lab-keys/tls/idp.ext -out .lab-keys/tls/idp.crt 2>/dev/null
  rm -f .lab-keys/tls/idp.csr .lab-keys/tls/idp.ext
fi
chmod 600 .lab-keys/tls/ca.key .lab-keys/tls/db.key
# The API (nobody) and Keycloak (uid 1000) read their keys from bind mounts:
# those key files are world-readable, protected by the 0700 .lab-keys/tls
# directory on the host.
chmod 644 .lab-keys/tls/ca.crt .lab-keys/tls/db.crt .lab-keys/tls/api.crt .lab-keys/tls/api.key \
  .lab-keys/tls/idp.crt .lab-keys/tls/idp.key
chmod 600 .env.lab
echo "Private .env.lab ready for the disposable laboratory stack ($added value(s) added)."
